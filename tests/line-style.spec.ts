import { expect, test } from '@playwright/test'

test('dashed and solid line styles apply to figures and arrows',async({page})=>{
 await page.goto('/')
 const shapes=page.locator('[data-shape-id]')
 const ids=()=>shapes.evaluateAll(elements=>Array.from(new Set(elements.map(element=>element.getAttribute('data-shape-id')))))
 await expect.poll(()=>shapes.count()).toBeGreaterThanOrEqual(10)
 const before=await ids()
 await page.getByRole('button',{name:'Фигуры'}).click()
 const menu=page.getByRole('dialog',{name:'Настройки инструмента'})
 await menu.getByRole('button',{name:'Пунктирная'}).click()
 await expect(menu.getByRole('button',{name:'Пунктирная'})).toHaveAttribute('aria-pressed','true')
 await page.mouse.move(400,750);await page.mouse.down();await page.mouse.move(600,850,{steps:6});await page.mouse.up()
 await expect.poll(async()=> (await ids()).filter(id=>!before.includes(id)).length).toBe(1)
 const shapeId=(await ids()).find(id=>!before.includes(id))
 const shape=page.locator(`[data-shape-id="${shapeId}"]`)
 await expect(shape.locator('[stroke-dasharray]').first()).toHaveAttribute('stroke-dasharray',/\d/)
 const afterShape=await ids()
 await page.getByRole('button',{name:'Стрелка'}).click()
 await expect(menu.getByRole('button',{name:'Пунктирная'})).toHaveAttribute('aria-pressed','true')
 await page.mouse.move(650,750);await page.mouse.down();await page.mouse.move(900,750,{steps:6});await page.mouse.up()
 await expect.poll(async()=> (await ids()).filter(id=>!afterShape.includes(id)).length).toBe(1)
 const arrowId=(await ids()).find(id=>!afterShape.includes(id))
 const arrow=page.locator(`[data-shape-id="${arrowId}"]`)
 await expect(arrow.locator('g[style*="clip-path"] path').first()).toHaveAttribute('stroke-dasharray',/\d/)
 const afterArrow=await ids()
 await menu.getByRole('button',{name:'Сплошная'}).click()
 await expect(menu.getByRole('button',{name:'Сплошная'})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Стрелка'}).click()
 await page.getByRole('button',{name:'Стрелка'}).click()
 await page.mouse.move(650,850);await page.mouse.down();await page.mouse.move(900,850,{steps:6});await page.mouse.up()
 await expect.poll(async()=> (await ids()).filter(id=>!afterArrow.includes(id)).length).toBe(1)
 const solidId=(await ids()).find(id=>!afterArrow.includes(id))
 const solid=page.locator(`[data-shape-id="${solidId}"]`)
 await expect(solid.locator('g[style*="clip-path"] path').first()).not.toHaveAttribute('stroke-dasharray',/\d/)
})
