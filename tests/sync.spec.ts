import { test, expect } from '@playwright/test'

test('two isolated clients synchronize edits and restore a room', async ({ browser }) => {
 const first=await browser.newContext(), second=await browser.newContext()
 const a=await first.newPage(), b=await second.newPage()
 const errors:string[]=[]
 for(const page of [a,b])page.on('pageerror',e=>errors.push(e.message))
 await a.goto('/dev-sync')
 await expect(a.getByText('Локальная доска')).toBeVisible()
 await a.getByRole('button',{name:'Добавить фигуру'}).click()
 await a.getByRole('button',{name:'Создать комнату'}).click()
 await expect(a.getByText('Общая доска')).toBeVisible()
 await expect(a.locator('.tl-canvas:visible')).toBeVisible()
 const url=a.url()
 await b.goto(url)
 await expect(b.locator('.tl-canvas')).toBeVisible()
 await expect.poll(()=>b.locator('[data-shape-id]').count()).toBe(1)
 await expect.poll(()=>a.evaluate(()=>(window as any).testEditor.store.allRecords().filter((r:any)=>r.typeName==='instance_presence').length)).toBeGreaterThan(0)
 await a.bringToFront()
 await a.mouse.move(500,400)
 await expect(b.locator('.tl-collaborator__cursor')).toBeVisible()
 await a.getByRole('button',{name:'Добавить фигуру'}).click()
 await expect.poll(()=>b.locator('[data-shape-id]').count()).toBe(2)
 await b.getByRole('button',{name:'Добавить фигуру'}).click()
 await expect.poll(()=>a.locator('[data-shape-id]:visible').count()).toBe(3)
 await Promise.all([a.getByRole('button',{name:'Добавить фигуру'}).click(),b.getByRole('button',{name:'Добавить фигуру'}).click()])
 await expect.poll(()=>a.locator('[data-shape-id]:visible').count()).toBe(5)
 await expect.poll(()=>b.locator('[data-shape-id]').count()).toBe(5)
 await a.getByRole('button',{name:'Добавить изображение'}).click()
 await expect.poll(()=>b.locator('[data-shape-id]').count()).toBe(6)
 const image=b.locator('img.tl-image')
 await expect(image).toBeVisible()
 await expect.poll(()=>image.evaluate((el:HTMLImageElement)=>el.complete&&el.naturalWidth>0)).toBe(true)
 await second.setOffline(true)
 await b.getByRole('button',{name:'Добавить фигуру'}).click()
 await expect.poll(()=>b.locator('[data-shape-id]').count()).toBe(7)
 await second.setOffline(false)
 await expect.poll(()=>a.locator('[data-shape-id]:visible').count(),{timeout:15000}).toBe(7)
 await first.close();await second.close()
 const third=await browser.newContext(), c=await third.newPage()
 await c.goto(url)
 await expect.poll(()=>c.locator('[data-shape-id]').count()).toBe(7)
 await expect.poll(()=>c.locator('img.tl-image').evaluate((el:HTMLImageElement)=>el.complete&&el.naturalWidth>0)).toBe(true)
 expect(errors).toEqual([])
 await third.close()
})


test('the board creates a local room without losing existing content', async ({ browser }) => {
 const first=await browser.newContext(), second=await browser.newContext()
 const a=await first.newPage(), b=await second.newPage(), errors:string[]=[]
 for(const page of [a,b])page.on('pageerror',e=>errors.push(e.message))
 await a.goto('/')
 await expect(a.getByRole('button',{name:'Пружина'})).toBeVisible()
 await a.getByRole('button',{name:'Пружина'}).click()
 const original=await a.locator('[data-shape-id]:visible').count()
 await a.getByRole('button',{name:'Локальная комната'}).click()
 await expect(a.getByText('Комната на этом компьютере')).toBeVisible()
 await expect.poll(()=>a.locator('[data-shape-id]:visible').count()).toBe(original)
 const url=a.url()
 await b.goto(url)
 await expect.poll(()=>b.locator('[data-shape-id]').count()).toBe(original)
 await b.getByRole('button',{name:'Резистор'}).click()
 await expect.poll(()=>a.locator('[data-shape-id]:visible').count()).toBeGreaterThan(original)
 await a.getByRole('button',{name:'На личную доску'}).click()
 await expect(a.getByText('Личная доска',{exact:true})).toBeVisible()
 await expect.poll(()=>a.locator('[data-shape-id]:visible').count()).toBe(original)
 expect(errors).toEqual([])
 await first.close();await second.close()
})


