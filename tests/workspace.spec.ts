import { expect, test } from '@playwright/test'

test('the workspace opens the existing board and keeps new boards separate', async ({ page }) => {
 await page.goto('/')
 await expect(page.getByRole('heading', { name: 'Мои доски' })).toBeVisible()
 await page.getByRole('link', { name: /Доска по физике/ }).click()
 const shapes = page.locator('[data-shape-id]:visible')
 await expect(shapes.first()).toBeVisible()
 const originalCount = await shapes.count()
 await page.getByRole('link', { name: 'Мои доски' }).click()

 await page.getByRole('button', { name: 'Новая доска' }).click()
 await page.getByLabel('Название доски').fill('Электричество')
 await page.getByRole('button', { name: 'Создать' }).click()
 await expect(page.getByRole('heading', { name: 'Электричество' })).toBeVisible()
 await expect(page.locator('.tl-canvas:visible')).toBeVisible()
 await expect(shapes).toHaveCount(0)
 await page.getByRole('button', { name: 'Резистор' }).click()
 await expect(shapes.first()).toBeVisible()
 const newCount = await shapes.count()
 await page.getByRole('link', { name: 'Мои доски' }).click()
 await page.getByRole('button', { name: 'Переименовать «Электричество»' }).click()
 await page.getByLabel('Название доски').fill('Электрические цепи')
 await page.getByRole('button', { name: 'Сохранить' }).click()
 await page.getByRole('link', { name: /Электрические цепи/ }).click()
 await expect(page.getByRole('heading', { name: 'Электрические цепи' })).toBeVisible()
 await expect(shapes).toHaveCount(newCount)
 await page.getByRole('button', { name: 'Пружина' }).click()
 await page.goBack()
 await page.getByRole('link', { name: /Электрические цепи/ }).click()
 await expect.poll(() => shapes.count()).toBeGreaterThan(newCount)
 await page.getByRole('link', { name: 'Мои доски' }).click()
 await page.getByRole('link', { name: /Доска по физике/ }).click()
 await expect(shapes).toHaveCount(originalCount)
})

test('the workspace saves a local profile and validates invitations', async ({ page }) => {
 await page.goto('/')
 await page.getByRole('button', { name: 'Профиль' }).click()
 await expect(page.getByLabel('Имя', { exact: true })).toBeFocused()
 await page.getByLabel('Имя', { exact: true }).fill('Алексей')
 await page.getByRole('button', { name: 'Сохранить' }).click()
 await page.reload()
 await expect(page.getByRole('button', { name: 'Профиль' })).toContainText('Алексей')
 await page.getByRole('button', { name: 'По ссылке' }).click()
 await page.getByLabel('Ссылка на доску').fill(`https://example.org/#cloud=${'a'.repeat(64)}`)
 await page.getByRole('button', { name: 'Открыть', exact: true }).click()
 await expect(page.getByRole('dialog').getByRole('alert')).toHaveText('Вставьте ссылку на совместную доску этого сайта.')
 await page.keyboard.press('Escape')
 await expect(page.getByRole('dialog')).toBeHidden()
})
