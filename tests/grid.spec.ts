import { test, expect } from '@playwright/test'

test('grid visibility and snapping can be changed independently and survive reload', async ({ page }) => {
  await page.goto(process.env.TEST_BASE_URL || '/')
  await page.getByRole('button', { name: 'Фон и сетка' }).click()
  const menu = page.getByRole('dialog', { name: 'Фон и сетка' })
  const grid = page.locator('.tl-background__wrapper .tl-grid')
  await expect(grid).toBeVisible()
  await expect(menu.getByRole('button', { name: 'Включена' })).toHaveAttribute('aria-pressed', 'true')

  await menu.getByRole('button', { name: 'Выключена' }).click()
  await expect(grid).toBeVisible()
  await expect(menu.getByRole('button', { name: 'Выключена' })).toHaveAttribute('aria-pressed', 'true')
  await menu.getByRole('button', { name: 'Без сетки' }).click()
  await expect(grid).toBeHidden()
  await menu.getByRole('button', { name: 'Включена' }).click()
  await expect(grid).toBeHidden()

  await page.reload()
  await page.getByRole('button', { name: 'Фон и сетка' }).click()
  await expect(grid).toBeHidden()
  await expect(menu.getByRole('button', { name: 'Включена' })).toHaveAttribute('aria-pressed', 'true')
  await menu.getByRole('button', { name: 'Сетка', exact: true }).click()
  await expect(grid).toBeVisible()
  await expect(grid.locator('path').first()).toHaveAttribute('d', /H 0 V/)
  const major = grid.locator('.graph-grid-major')
  await expect(major).toBeHidden()
  await menu.getByRole('button', { name: 'Миллиметровка' }).click()
  await expect(major).toBeVisible()
  await expect(menu.getByRole('button', { name: 'Миллиметровка' })).toHaveAttribute('aria-pressed', 'true')
  const widths = await grid.locator('pattern').evaluateAll(patterns => patterns.slice(0, 2).map(pattern => Number(pattern.getAttribute('width'))))
  expect(widths[1]).toBeCloseTo(widths[0] * 5)
  await page.reload()
  await page.getByRole('button', { name: 'Фон и сетка' }).click()
  await expect(major).toBeVisible()
  await expect(menu.getByRole('button', { name: 'Миллиметровка' })).toHaveAttribute('aria-pressed', 'true')
  await menu.getByRole('button', { name: 'Тетрадь' }).click()
  await expect(major).toBeHidden()
})

test('grid snapping changes the position of newly drawn shapes', async ({ page }) => {
  await page.goto(process.env.TEST_BASE_URL || '/')
  await page.getByRole('button', { name: 'Фон и сетка' }).click()
  const menu = page.getByRole('dialog', { name: 'Фон и сетка' })
  await menu.getByRole('button', { name: 'Выключена' }).click()
  await menu.getByRole('button', { name: 'Закрыть' }).click()
  const shapes = page.locator('[data-shape-id]')
  const ids = async () => shapes.evaluateAll(elements => elements.map(element => element.getAttribute('data-shape-id')))
  const before = await ids()
  await page.getByRole('button', { name: 'Фигуры' }).click()
  await page.mouse.move(550, 350)
  await page.mouse.down()
  await page.mouse.move(620, 420, { steps: 5 })
  await page.mouse.up()
  const position = async (previous: (string | null)[]) => {
    const created = (await ids()).find(id => !previous.includes(id))
    expect(created).toBeTruthy()
    return page.locator(`[data-shape-id="${created}"]`).evaluate(element => {
    const matrix = new DOMMatrix(getComputedStyle(element).transform)
    return [matrix.e, matrix.f]
    })
  }
  const free = await position(before)
  expect(free.some(value => Math.abs(value / 10 - Math.round(value / 10)) > 0.001)).toBe(true)
  await page.getByRole('button', { name: 'Фон и сетка' }).click()
  await menu.getByRole('button', { name: 'Включена' }).click()
  await menu.getByRole('button', { name: 'Закрыть' }).click()
  const afterFree = await ids()
  await page.getByRole('button', { name: 'Фигуры' }).click()
  await page.mouse.move(650, 450)
  await page.mouse.down()
  await page.mouse.move(720, 520, { steps: 5 })
  await page.mouse.up()
  const snapped = await position(afterFree)
  expect(snapped.every(value => Math.abs(value / 10 - Math.round(value / 10)) < 0.001)).toBe(true)
})
